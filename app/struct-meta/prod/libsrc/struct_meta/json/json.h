#ifndef JSON_PRIVATE_H
#define JSON_PRIVATE_H

/**
 *  JSON で正確に扱える整数の絶対値の上限です。
 *
 *  cJSON の数値は `double` です。さらに cJSON の出力は `%1.15g` を試し、
 *  元の `double` へ戻せるかを `compare_double()` で確かめますが、この判定は
 *  相対イプシロン (`fabs(a - b) <= maxVal * DBL_EPSILON`) であり 1 ULP の差を
 *  許容します。そのため 15 桁を超える整数は、出力して読み戻すと値が変わります。\n
 *  実測では 9007199254740992 (2^53) が `9.00719925474099e+15` として出力され、
 *  読み戻すと 9007199254740990 になりました。\n
 *  そこで上限を 15 桁 (10^15 - 1) とし、`struct_meta` が受け付けた整数は必ず
 *  そのまま読み戻せるようにします。
 *
 *  比較は整数のまま行ってください。`double` へ変換してから比較すると境界で
 *  丸めが起き、検査が漏れます。
 */
#define STRUCT_META_JSON_INTEGER_LIMIT 999999999999999

#endif /* JSON_PRIVATE_H */
